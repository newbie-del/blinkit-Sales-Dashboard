"""
Step 1 - Data profiling / audit
===============================

Reads the raw CSV and reports, without changing it:
  columns & inferred types, missing values, duplicates, invalid values,
  inconsistent categories, outliers, and referential consistency.

Output: printed report + `Reports/data_quality_report.md`

Run: python Scripts/02_profile_dataset.py
"""

from __future__ import annotations

import io
import sys
from collections import Counter
from pathlib import Path

import pandas as pd

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[1]
CSV = ROOT / "Dataset" / "BlinkIT Grocery Data.csv"
REPORT = ROOT / "Reports" / "data_quality_report.md"

buf = io.StringIO()


def out(line: str = "") -> None:
    print(line)
    buf.write(line + "\n")


def rule(title: str) -> None:
    out()
    out(f"## {title}")
    out()


df = pd.read_csv(CSV, dtype=str, keep_default_na=False, na_values=[""])
raw_rows = len(df)

out("# Blinkit Grocery Data - Data Quality Report")
out()
out(f"- Source file: `Dataset/{CSV.name}`")
out(f"- Rows: **{raw_rows:,}**")
out(f"- Columns: **{df.shape[1]}**")
out()
out("Generated by `Scripts/02_profile_dataset.py`. The raw file is never modified.")

# --------------------------------------------------------------------------
rule("1. Schema and inferred types")

num_cols = ["Item Weight", "Item Visibility", "Sales", "Rating",
            "Outlet Establishment Year"]
numeric = {c: pd.to_numeric(df[c], errors="coerce") for c in num_cols}

out("| # | Column | Stored as | Should be | Role |")
out("|---|--------|-----------|-----------|------|")
roles = [
    ("Item Identifier", "text", "VARCHAR(10)", "Product key (dimension)"),
    ("Item Weight", "text w/ blanks", "DECIMAL(6,3)", "Product attribute"),
    ("Item Fat Content", "text", "VARCHAR(10)", "Category (needs cleaning)"),
    ("Item Visibility", "text", "DECIMAL(9,6)", "Shelf-share metric"),
    ("Item Type", "text", "VARCHAR(40)", "Category (dimension)"),
    ("Outlet Identifier", "text", "CHAR(6)", "Store key (dimension)"),
    ("Outlet Establishment Year", "text", "SMALLINT", "Store attribute"),
    ("Outlet Size", "text w/ blanks", "VARCHAR(10)", "Category (dimension)"),
    ("Outlet Location Type", "text", "VARCHAR(10)", "Category (dimension)"),
    ("Outlet Type", "text", "VARCHAR(25)", "Category (dimension)"),
    ("Sales", "text", "DECIMAL(10,4)", "**Primary measure (INR)**"),
    ("Rating", "text", "DECIMAL(3,2)", "Measure (1-5 scale)"),
    ("Order Date", "text", "DATE", "Time dimension"),
]
for i, (c, stored, should, role) in enumerate(roles, 1):
    out(f"| {i} | `{c}` | {stored} | `{should}` | {role} |")

out()
out("**Issue.** Everything arrives as text because CSV has no type system. "
    "Loading numerics as text would break every SUM, AVG and date filter, so "
    "types are declared explicitly in `SQL/Database.sql` rather than left to "
    "the import wizard to guess.")

# --------------------------------------------------------------------------
rule("2. Missing values")

miss = df.isna().sum()
out("| Column | Missing | % of rows | Interpretation |")
out("|--------|---------|-----------|----------------|")
notes = {
    "Item Weight": "Genuinely absent - not captured at product onboarding.",
    "Outlet Size": "Absent for 3 outlets that never reported a size band.",
}
any_missing = False
for c in df.columns:
    if miss[c]:
        any_missing = True
        out(f"| `{c}` | {miss[c]:,} | {miss[c]/raw_rows*100:.2f}% | "
            f"{notes.get(c, 'Unexpected - investigate.')} |")
if not any_missing:
    out("| - | 0 | 0% | No blank cells |")

blank_size_outlets = sorted(df.loc[df["Outlet Size"].isna(), "Outlet Identifier"].unique())
out()
out(f"Outlets with no size recorded: **{', '.join(blank_size_outlets)}**")
out()
out("**Why it matters.** `Item Weight` is missing on roughly a sixth of rows. "
    "Dropping those rows would discard ~17% of revenue and bias every category "
    "total. `Outlet Size` is missing for whole outlets, so it cannot be imputed "
    "from other rows of the same outlet - a deliberate `Unknown` band is the "
    "honest treatment, and it keeps those outlets in the revenue totals.")

# --------------------------------------------------------------------------
rule("3. Duplicate rows")

full_dupes = df.duplicated(keep=False).sum()
extra = df.duplicated().sum()
grain_dupes = df.duplicated(subset=["Item Identifier", "Outlet Identifier"]).sum()
out(f"- Fully identical rows involved in a duplicate group: **{full_dupes}**")
out(f"- Redundant copies to remove: **{extra}**")
out(f"- Duplicates on the business grain (Item x Outlet): **{grain_dupes}**")
out()
out("**Why it matters.** The grain of this table is one row per product per "
    "outlet. Exact duplicates are a re-submitted ETL batch; each one "
    "double-counts its sales value and inflates revenue. They are removed in "
    "cleaning, keyed on the full row so no legitimate record is lost.")

# --------------------------------------------------------------------------
rule("4. Inconsistent categories")

fat = Counter(df["Item Fat Content"])
out("`Item Fat Content` - distinct raw values:")
out()
out("| Raw value (quoted) | Rows | Canonical |")
out("|--------------------|------|-----------|")
canon = {"low fat": "Low Fat", "lf": "Low Fat", "reg": "Regular"}
for v, n in fat.most_common():
    target = canon.get(v.strip().lower(), v.strip().title())
    flag = "" if v == target else " ⚠"
    out(f"| `\"{v}\"` | {n:,} | {target}{flag} |")
n_lowfat = sum(1 for v in fat if canon.get(v.strip().lower(), v.strip().title()) == "Low Fat")
n_reg = len(fat) - n_lowfat
out()
out(f"**{len(fat)} raw spellings collapse to 2 real categories.** Left as-is, "
    f"a `GROUP BY Item Fat Content` returns {len(fat)} rows and splits Low Fat "
    f"revenue across {n_lowfat} buckets and Regular across {n_reg}, so any "
    "fat-content chart is simply wrong. Note the trailing/leading spaces - "
    "these are invisible in a spreadsheet and are the classic cause of "
    "'my totals don't match'.")

for col in ["Item Type", "Outlet Size", "Outlet Location Type", "Outlet Type",
            "Outlet Identifier"]:
    vals = df[col].dropna().unique()
    out()
    out(f"`{col}` - {len(vals)} distinct: {', '.join(sorted(vals))}")

ws = {c: int(df[c].dropna().str.strip().ne(df[c].dropna()).sum())
      for c in df.columns}
ws = {k: v for k, v in ws.items() if v}
out()
out("Columns containing untrimmed whitespace: "
    + (", ".join(f"`{k}` ({v:,} rows)" for k, v in ws.items()) or "none"))

# --------------------------------------------------------------------------
rule("5. Invalid and impossible values")

vis = numeric["Item Visibility"]
sales = numeric["Sales"]
rating = numeric["Rating"]
wt = numeric["Item Weight"]

zero_vis = int((vis == 0).sum())
out(f"- `Item Visibility` = 0.00: **{zero_vis:,} rows "
    f"({zero_vis/raw_rows*100:.2f}%)**. A product that is stocked and selling "
    "cannot occupy 0% of shelf space. This is a *sentinel for 'not recorded'*, "
    "not a true zero.")
out(f"- `Item Visibility` outside [0, 1]: **{int(((vis < 0) | (vis > 1)).sum())}** "
    "(it is a proportion, so anything outside this range is corrupt).")
out(f"- `Sales` <= 0: **{int((sales <= 0).sum())}** (a sale must be positive).")
n_bad_rating = int(((rating < 1) | (rating > 5)).sum())
out(f"- `Rating` outside [1, 5]: **{n_bad_rating}** (the collection scale is "
    "1-5). Caused by the over-precision below nudging a 5.0 past the ceiling; "
    "cleaning clamps to the valid range.")
over_precise = int((df["Rating"].dropna().str.split(".").str[-1].str.len() > 1).sum())
out(f"- `Rating` with >1 decimal place: **{over_precise:,} rows**. Ratings are "
    "collected on a 1-decimal scale; extra digits are float artefacts from an "
    "upstream average and imply precision that does not exist.")
out(f"- `Item Weight` <= 0: **{int((wt <= 0).sum())}**.")

yr = numeric["Outlet Establishment Year"]
out(f"- `Outlet Establishment Year` range: **{int(yr.min())}-{int(yr.max())}** "
    "- plausible, no future or placeholder years.")

d = pd.to_datetime(df["Order Date"], errors="coerce")
out(f"- `Order Date` unparseable: **{int(d.isna().sum())}**; "
    f"range **{d.min():%Y-%m-%d} to {d.max():%Y-%m-%d}**.")
out(f"- Orders dated before their outlet opened: "
    f"**{int((d.dt.year < yr).sum())}** (logical cross-field check).")

# --------------------------------------------------------------------------
rule("6. Referential consistency")

per_outlet = df.groupby("Outlet Identifier").agg(
    sizes=("Outlet Size", lambda s: s.fillna("(blank)").nunique()),
    tiers=("Outlet Location Type", "nunique"),
    types=("Outlet Type", "nunique"),
    years=("Outlet Establishment Year", "nunique"),
)
bad = per_outlet[(per_outlet > 1).any(axis=1)]
out(f"- Outlets whose attributes disagree across rows: **{len(bad)}** "
    "(each outlet must have exactly one size, tier, type and year).")

w_per_item = df.dropna(subset=["Item Weight"]).groupby("Item Identifier")["Item Weight"].nunique()
out(f"- Items with conflicting weights across outlets: "
    f"**{int((w_per_item > 1).sum())}** (weight is a property of the product).")
t_per_item = df.groupby("Item Identifier")["Item Type"].nunique()
out(f"- Items assigned to more than one Item Type: **{int((t_per_item > 1).sum())}**.")
out()
out("**Why it matters.** These checks prove the table can be split into clean "
    "product and outlet dimensions. If an outlet reported two different sizes, "
    "no store-level roll-up could be trusted.")

# --------------------------------------------------------------------------
rule("7. Outliers in Sales")

q1, q3 = sales.quantile(.25), sales.quantile(.75)
iqr = q3 - q1
lo, hi = q1 - 1.5 * iqr, q3 + 1.5 * iqr
n_out = int(((sales < lo) | (sales > hi)).sum())
out("| Statistic | Value (INR) |")
out("|-----------|-------------|")
for label, v in [("Min", sales.min()), ("Q1", q1), ("Median", sales.median()),
                 ("Mean", sales.mean()), ("Q3", q3), ("Max", sales.max()),
                 ("Std dev", sales.std())]:
    out(f"| {label} | {v:,.2f} |")
out(f"| IQR upper fence | {hi:,.2f} |")
out(f"| Rows above fence | {n_out:,} ({n_out/raw_rows*100:.2f}%) |")
out()
out(f"Mean ({sales.mean():,.0f}) sits above the median ({sales.median():,.0f}), "
    "so the distribution is right-skewed - a long tail of large baskets. "
    "**These outliers are kept.** In grocery retail a high-value basket is a "
    "real event, usually a Supermarket Type3 festive order, and it is exactly "
    "what the business wants to understand. They are flagged, not deleted; "
    "median is reported alongside mean so the skew stays visible.")

# --------------------------------------------------------------------------
rule("8. Cleaning decisions")

out("| # | Issue | Decision | Rationale |")
out("|---|-------|----------|-----------|")
dec = [
    ("5 spellings of fat content", "Map to `Low Fat` / `Regular`; TRIM all text",
     "Without it every fat-content aggregate splits across duplicate buckets."),
    (f"{miss['Item Weight']:,} missing Item Weight",
     "Impute with the item's own median, else its Item Type median",
     "Keeps ~17% of revenue in scope. Item-level median first because weight is "
     "a product property; type median is the fallback for never-weighed SKUs."),
    ("Missing Outlet Size", "Label `Unknown` (do not guess)",
     "Missing for whole outlets, so nothing to impute from. A visible `Unknown` "
     "band is auditable; a guess silently distorts size analysis."),
    (f"{zero_vis:,} zero visibility", "Treat as NULL, impute item-type median; keep a flag",
     "0% shelf space is impossible for a selling product. Averaging real zeros "
     "would understate visibility and weaken the visibility-sales relationship."),
    (f"{extra} duplicate rows", "Delete redundant copies, keep one",
     "Each copy double-counts revenue."),
    ("Rating over-precision", "Round to 1 decimal",
     "Matches the actual collection scale."),
    ("Right-skewed Sales", "Keep; flag outliers; report median too",
     "High-value baskets are real business events, not errors."),
    ("Text-typed numerics/dates", "Declare real types in DDL",
     "Enables SUM/AVG, date maths and index use."),
]
for i, (iss, act, why) in enumerate(dec, 1):
    out(f"| {i} | {iss} | {act} | {why} |")

out()
out("**Golden rule.** The raw CSV is loaded into a staging table and never "
    "written to. Cleaning produces a separate analytics table, so the pipeline "
    "is re-runnable and every transformation is auditable.")

REPORT.parent.mkdir(parents=True, exist_ok=True)
REPORT.write_text(buf.getvalue(), encoding="utf-8")
print(f"\n[saved] {REPORT}")
